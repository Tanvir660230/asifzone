/** String keys are what `HomepageSection.config` stores (JSON can't hold a component reference) —
 * this is the single lookup both the storefront (TrustStrip/ValuesGrid) and the admin builder's
 * icon picker resolve against, so the two stay in sync. Curated (not the full ~1500-icon Lucide
 * set) to keep the picker scannable — every entry here should be plausible on a trust badge or
 * value-prop card for a clothing store. */
