export const HOMEPAGE_ICON_NAMES = Object.keys(HOMEPAGE_ICON_MAP);

export function resolveHomepageIcon(name: string): LucideIcon {
  return HOMEPAGE_ICON_MAP[name] ?? Sparkles;
}
